def build_skills_message(names: list[str]) -> str:
    """按 Router 判定的意图注入 skill。不传就什么都不注入 —— 省 token。"""
    blocks = [SKILLS[n].strip() for n in names if n in SKILLS]
    return "\n\n".join(blocks)
